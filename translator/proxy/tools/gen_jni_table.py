# Generates jni_table.inc from the real jni.h: usage gen_jni_table.py jni.h > jni_table.inc
import re, sys
src = open(sys.argv[1]).read()
body = re.search(r'struct JNINativeInterface \{(.*?)\n\};', src, re.S).group(1)
body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
body = re.sub(r'//[^\n]*', '', body)
decls = [re.sub(r'\s+', ' ', d).strip() for d in body.split(';') if d.strip()]
simple = {'jint':'i','jsize':'i','jobjectRefType':'i','jboolean':'z','jbyte':'b','jchar':'c','jshort':'h',
          'jlong':'l','jfloat':'f','jdouble':'d','void':'v','va_list':'V','...':'.'}
def ch(t):
    t = re.sub(r'\bconst\b', '', t).strip()
    if '*' in t: return 'p'
    return simple.get(t, 'p')   # jobject, jclass, jmethodID, ... : opaque pointers
out = ['// SPDX-License-Identifier: GPL-2.0-or-later', '// GENERATED by tools/gen_jni_table.py from jni.h; do not edit.',
       '// JNI_FN(name, ret, "args"); args: p ptr, i int, z/b/c/h bool/byte/char/short, l long, f, d, V va_list, . varargs']
n = 0
for d in decls:
    m = re.match(r'void\* (reserved\d)$', d)
    if m: out.append('JNI_RESERVED(%s)' % m.group(1)); n += 1; continue
    m = re.match(r'(.*?)\(\*(\w+)\)\((.*)\)$', d)
    assert m, d
    ret, name, args = m.group(1).strip(), m.group(2), m.group(3)
    a = ''.join(ch(x) for x in args.split(','))
    out.append('JNI_FN(%s, \'%s\', "%s")' % (name, ch(ret), a)); n += 1
out.append('// entries: %d' % n)
print('\n'.join(out))
