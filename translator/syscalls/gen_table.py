# Regenerates a64_nr.h and a64_table.inc from the kernel's arm64 syscall table.
# usage: gen_table.py /mnt/storage-adata/kernel/common/arch/arm64/tools/syscall_64.tbl
# ABIs built for arm64 64-bit: see arch/arm64/kernel/Makefile.syscalls (common 64 renameat rlimit memfd_secret).
import sys
ABIS = {"common", "64", "renameat", "rlimit", "memfd_secret"}
rows = []
for l in open(sys.argv[1]):
    if l.startswith("#") or not l.strip():
        continue
    f = l.split()
    if f[1] in ABIS:
        rows.append((int(f[0]), f[2]))
hdr = "// SPDX-License-Identifier: GPL-2.0-or-later\n// GENERATED by gen_table.py from arch/arm64/tools/syscall_64.tbl. Do not edit.\n#pragma once\n"
open("a64_nr.h", "w").write(hdr + "".join("#define A64_%s %d\n" % (n, v) for v, n in rows))
with open("a64_table.inc", "w") as o:
    o.write("// SPDX-License-Identifier: GPL-2.0-or-later\n// GENERATED by gen_table.py. Entries: {aarch64 nr, name, host x86_64 nr or -1}\n")
    for v, n in rows:
        o.write('#ifdef __NR_%s\n{%d,"%s",__NR_%s},\n#else\n{%d,"%s",-1},\n#endif\n' % (n, v, n, n, v, n))
print(len(rows), "entries")
